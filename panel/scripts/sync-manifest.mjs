import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const panelDir = resolve(scriptDir, '..');
const repoDir = resolve(panelDir, '..');
const configPath = resolve(repoDir, 'config/config.json');
const mappingPath = resolve(repoDir, 'config/knx-mapping.json');
const planPath = resolve(repoDir, 'data/tuya-gateway-dp-plan.json');
const generatedDir = resolve(panelDir, 'src/generated');

const [runtimeConfig, mappingSource, plan] = await Promise.all([
  readJSON(configPath),
  readJSON(mappingPath),
  readJSON(planPath),
]);
const mappings = Array.isArray(mappingSource)
  ? mappingSource
  : mappingSource.mappings;
const manifest = buildManifest(mappings);
const runtimeBundleURL =
  runtimeConfig.runtime_update?.remote_url ||
  'https://gitee.com/api/v5/repos/mvptianyu/config-gateway/contents/knx/knx-mapping.json?ref=master';
const runtimeBundlePollSeconds = Math.max(
  60,
  Number(runtimeConfig.runtime_update?.remote_poll_seconds) || 300
);

if (!runtimeBundleURL.startsWith('https://')) {
  throw new Error(`Panel runtime bundle URL must use HTTPS: ${runtimeBundleURL}`);
}

if (!Array.isArray(mappings)) {
  throw new Error(`Unsupported runtime mapping: ${mappingPath}`);
}
if (!Array.isArray(plan.functions)) {
  throw new Error(`Invalid gateway DP plan: ${planPath}`);
}

const functionsByCode = new Map(plan.functions.map(item => [item.code, item]));
for (const device of manifest.devices) {
  for (const code of Object.values(device.dps)) {
    if (!functionsByCode.has(code)) {
      throw new Error(`Panel device ${device.id} references unknown DP code ${code}`);
    }
  }
}

await mkdir(generatedDir, { recursive: true });
await Promise.all([
  writeFile(
    resolve(generatedDir, 'manifest.ts'),
    generatedManifest(manifest),
    'utf8'
  ),
  writeFile(
    resolve(generatedDir, 'schema.ts'),
    generatedSchema(plan.functions),
    'utf8'
  ),
  writeFile(
    resolve(generatedDir, 'runtime.ts'),
    generatedRuntime(runtimeBundleURL, runtimeBundlePollSeconds),
    'utf8'
  ),
]);

console.log(
  `Panel config synced: ${manifest.devices.length} mapped devices, ${plan.functions.length} DP definitions`
);

async function readJSON(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

function generatedManifest(manifest) {
  return `// Generated by scripts/sync-manifest.mjs. Do not edit manually.
import { PanelDevice } from '@/types';

export const panelManifest = ${JSON.stringify(manifest, null, 2)} as const;

export const panelDevices = panelManifest.devices as unknown as PanelDevice[];
`;
}

function generatedRuntime(remoteURL, pollSeconds) {
  return `// Generated by scripts/sync-manifest.mjs. Do not edit manually.
export const runtimeBundleURL = ${JSON.stringify(remoteURL)};
export const runtimeBundlePollSeconds = ${JSON.stringify(pollSeconds)};
`;
}

function buildManifest(mappings) {
  if (!Array.isArray(mappings)) {
    return { version: 1, devices: [] };
  }
  const devices = new Map();
  for (const item of mappings) {
    if (!item.virtual_device_id || !item.category || !item.slot || !item.capability) {
      continue;
    }
    const key = `${item.category}\u0000${item.slot}`;
    const room = item.room || '全屋';
    const existing = devices.get(key);
    if (existing) {
      if (
        existing.id !== item.virtual_device_id ||
        existing.name !== item.name ||
        existing.room !== room
      ) {
        throw new Error(`Inconsistent runtime device ${key}`);
      }
      existing.dps[item.capability] = item.tuya_dp_code;
      continue;
    }
    devices.set(key, {
      id: item.virtual_device_id,
      name: item.name,
      category: item.category,
      room,
      slot: item.slot,
      dps: { [item.capability]: item.tuya_dp_code },
    });
  }
  return {
    version: 1,
    devices: Array.from(devices.values()).sort(
      (left, right) =>
        left.category.localeCompare(right.category) || left.slot - right.slot
    ),
  };
}

function generatedSchema(functions) {
  const schema = functions.map(item => {
    const property = { type: item.type };
    if (item.type === 'enum') {
      property.range = item.enum_values || [];
    }
    if (item.type === 'value') {
      Object.assign(property, {
        min: item.value_spec.min,
        max: item.value_spec.max,
        step: item.value_spec.step,
        scale: item.value_spec.scale,
        unit: item.value_spec.unit,
      });
    }
    return {
      code: item.code,
      id: item.dp_id,
      mode: item.access,
      name: item.name,
      property,
      type: 'obj',
    };
  });

  return `// Generated by scripts/sync-manifest.mjs. Do not edit manually.
export const defaultSchema = ${JSON.stringify(schema, null, 2)} as const;
`;
}
